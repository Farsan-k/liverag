
from pathlib import Path

from app.pdf_extractor import extract_pdf_text


def test_financial_page_extraction():
    result = extract_pdf_text(
        Path("data/raw/apple_10K.pdf")
    )

    financial_pages = {
        32: [
            "CONSOLIDATED STATEMENTS OF OPERATIONS",
            "Net sales",
            "Net income",
        ],
        34: [
            "CONSOLIDATED BALANCE SHEETS",
            "Total assets",
            "Total liabilities",
        ],
        36: [
            "CONSOLIDATED STATEMENTS OF CASH FLOWS",
            "Operating activities",
            "Cash generated by operating activities",
        ],
        39: [
            "disaggregated net sales",
            "iPhone",
            "Services",
            "Total net sales",
        ],
    }

    for page_number, expected_terms in financial_pages.items():
        page = result["pages"][page_number - 1]
        page_text = page["text"]

        print("\n" + "=" * 70)
        print("PDF PAGE:", page_number)
        print("CHARACTERS:", page["character_count"])

        assert page_text.strip(), (
            f"PDF page {page_number} is empty"
        )

        for term in expected_terms:
            assert term.lower() in page_text.lower(), (
                f"Missing expected content on PDF page "
                f"{page_number}: {term}"
            )

        print("Validated terms:", expected_terms)
        print("Financial page validation: PASSED")
